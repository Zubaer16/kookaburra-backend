import { expect, test, type APIRequestContext } from '@playwright/test'
import { JwtService } from '@nestjs/jwt'
import { PrismaPg } from '@prisma/adapter-pg'
import { randomBytes, randomUUID, createHash } from 'node:crypto'
import { PrismaClient } from '../src/generated/prisma/client'

/**
 * Real HTTP + Prisma security regression tests. The launcher strictly confines
 * this suite to local PostgreSQL database kookaburra_api_test.
 * Never run this file with an arbitrary Playwright command or a dev/live DB.
 */
type Credentials = { email: string; password: string }
type Registered = { user: { id: string; email: string; role: string }; accessToken: string; refreshToken: string }

function isolatedDatabaseUrl(): string {
  if (
    process.env.API_TEST_MODE !== 'db' ||
    process.env.API_TEST_PORT !== '4101' ||
    !process.env.DATABASE_URL
  ) {
    throw new Error('Run using npm run test:api:security only')
  }
  const url = new URL(process.env.DATABASE_URL)
  if (
    !['postgres:', 'postgresql:'].includes(url.protocol) ||
    !['localhost', '127.0.0.1', '[::1]'].includes(url.hostname.toLowerCase()) ||
    decodeURIComponent(url.pathname.slice(1)) !== 'kookaburra_api_test'
  ) {
    throw new Error('Security tests refuse development, staging and live databases')
  }
  return process.env.DATABASE_URL
}

function prisma(): PrismaClient {
  return new PrismaClient({
    adapter: new PrismaPg({ connectionString: isolatedDatabaseUrl() }),
  })
}

function credentials(): Credentials {
  return {
    email: `security-${randomUUID()}@example.test`,
    password: `Security-${randomBytes(18).toString('hex')}!`,
  }
}

async function withRegisteredCustomer(
  request: APIRequestContext,
  run: (account: Credentials, tokens: Registered) => Promise<void>,
): Promise<void> {
  const account = credentials()
  try {
    const response = await request.post('/v1/auth/register', { data: account })
    expect(response.status()).toBe(201)
    const tokens = (await response.json()) as Registered
    expect(tokens.user).toMatchObject({ email: account.email, role: 'CUSTOMER' })
    await run(account, tokens)
  } finally {
    // Only delete records with the unique prefix generated by this test.
    const client = prisma()
    try {
      const user = await client.user.findUnique({ where: { email: account.email } })
      if (user) {
        await client.auditEvent.deleteMany({ where: { actorId: user.id } })
        await client.user.delete({ where: { id: user.id } })
      }
    } finally {
      await client.$disconnect()
    }
  }
}

async function signedAccessToken(
  id: string,
  overrides: { expiresIn?: number; issuer?: string; audience?: string; typ?: string; secret?: string } = {},
): Promise<string> {
  const secret = overrides.secret ?? process.env.JWT_ACCESS_SECRET
  if (!secret || secret.length < 32) throw new Error('Missing isolated test JWT signing secret')
  const jwt = new JwtService()
  return jwt.signAsync(
    { sub: id, typ: overrides.typ ?? 'access' },
    {
      secret,
      algorithm: 'HS256',
      issuer: overrides.issuer ?? 'commerce-api',
      audience: overrides.audience ?? 'commerce-clients',
      expiresIn: overrides.expiresIn ?? 60,
    },
  )
}

const bearer = (token: string) => ({ Authorization: `Bearer ${token}` })

// These are separate tests, so the HTML report identifies *which* rule failed.
test.describe('Phase 02 security and negative cases — isolated real PostgreSQL', () => {
  test('Customer registration returns limited identity data, not password hash', async ({ request }) => {
    await withRegisteredCustomer(request, async (_account, tokens) => {
      expect(tokens.user.role).toBe('CUSTOMER')
      expect(tokens.user).not.toHaveProperty('passwordHash')
      expect(tokens).not.toHaveProperty('passwordHash')
      expect(tokens.accessToken.length).toBeGreaterThan(50)
      expect(tokens.refreshToken.length).toBeGreaterThan(20)
      expect((tokens as Registered & { tokenType?: string }).tokenType).toBe('Bearer')
    })
  })

  test('Duplicate emails are rejected without creating another account', async ({ request }) => {
    await withRegisteredCustomer(request, async (account) => {
      const duplicate = await request.post('/v1/auth/register', { data: account })
      expect(duplicate.status()).toBe(409)
      const client = prisma()
      try {
        expect(await client.user.count({ where: { email: account.email } })).toBe(1)
      } finally { await client.$disconnect() }
    })
  })

  test('Registration cannot assign OWNER or unexpected properties', async ({ request }) => {
    const response = await request.post('/v1/auth/register', {
      data: { ...credentials(), role: 'OWNER', status: 'ACTIVE' },
    })
    expect(response.status()).toBe(400)
  })

  test('Login rejects an unknown email with a generic 401', async ({ request }) => {
    const response = await request.post('/v1/auth/login', { data: credentials() })
    expect(response.status()).toBe(401)
    expect(JSON.stringify(await response.json())).not.toMatch(/passwordHash|postgres|PrismaClient/i)
  })

  test('Login rejects a valid user with the wrong password', async ({ request }) => {
    await withRegisteredCustomer(request, async (account) => {
      const response = await request.post('/v1/auth/login', {
        data: { email: account.email, password: `Wrong-${randomBytes(18).toString('hex')}!` },
      })
      expect(response.status()).toBe(401)
    })
  })

  test('Registration normalizes email case and protects against case-duplicate signup', async ({ request }) => {
    const account = credentials()
    const uppercase = account.email.toUpperCase()
    try {
      const response = await request.post('/v1/auth/register', {
        data: { ...account, email: uppercase },
      })
      expect(response.status()).toBe(201)
      expect((await response.json()).user.email).toBe(account.email)
      const duplicate = await request.post('/v1/auth/register', { data: account })
      expect(duplicate.status()).toBe(409)
    } finally {
      const client = prisma()
      try {
        await client.user.deleteMany({ where: { email: account.email } })
      } finally { await client.$disconnect() }
    }
  })

  test('Expired access JWT is rejected', async ({ request }) => {
    await withRegisteredCustomer(request, async (_account, tokens) => {
      const expired = await signedAccessToken(tokens.user.id, { expiresIn: -10 })
      const response = await request.get('/v1/auth/me', { headers: bearer(expired) })
      expect(response.status()).toBe(401)
    })
  })

  test('Wrong-signature JWT is rejected', async ({ request }) => {
    await withRegisteredCustomer(request, async (_account, tokens) => {
      const forged = await signedAccessToken(tokens.user.id, {
        secret: randomBytes(48).toString('hex'),
      })
      const response = await request.get('/v1/auth/me', { headers: bearer(forged) })
      expect(response.status()).toBe(401)
    })
  })

  test('Wrong issuer, audience and token type are rejected', async ({ request }) => {
    await withRegisteredCustomer(request, async (_account, tokens) => {
      const invalidOptions = [
        { issuer: 'another-service' },
        { audience: 'another-client' },
        { typ: 'refresh' },
      ]
      for (const options of invalidOptions) {
        const forged = await signedAccessToken(tokens.user.id, options)
        expect((await request.get('/v1/auth/me', { headers: bearer(forged) })).status()).toBe(401)
      }
    })
  })

  test('Malformed Authorization header and opaque refresh token are rejected', async ({ request }) => {
    for (const path of ['/v1/auth/me', '/v1/admin/auth/me']) {
      for (const header of ['Basic abc', 'Bearer abc', 'Bearer', 'Bearer token with spaces']) {
        expect((await request.get(path, { headers: { Authorization: header } })).status()).toBe(401)
      }
    }
    expect((await request.post('/v1/auth/refresh', { data: { refreshToken: 'bad' } })).status()).toBe(400)
    expect((await request.post('/v1/auth/refresh', {
      data: { refreshToken: randomBytes(48).toString('base64url') },
    })).status()).toBe(401)
  })

  test('Disabled account cannot login, use an access JWT, or refresh', async ({ request }) => {
    await withRegisteredCustomer(request, async (account, tokens) => {
      const client = prisma()
      try {
        await client.user.update({ where: { id: tokens.user.id }, data: { status: 'DISABLED' } })
      } finally { await client.$disconnect() }
      expect((await request.post('/v1/auth/login', { data: account })).status()).toBe(401)
      expect((await request.get('/v1/auth/me', { headers: bearer(tokens.accessToken) })).status()).toBe(401)
      expect((await request.post('/v1/auth/refresh', {
        data: { refreshToken: tokens.refreshToken },
      })).status()).toBe(401)
    })
  })

  test('Expired refresh token cannot mint a new pair', async ({ request }) => {
    await withRegisteredCustomer(request, async (_account, tokens) => {
      const tokenHash = createHash('sha256').update(tokens.refreshToken).digest('hex')
      const client = prisma()
      try {
        await client.authSession.update({
          where: { tokenHash },
          data: { expiresAt: new Date(Date.now() - 60_000) },
        })
      } finally { await client.$disconnect() }
      const response = await request.post('/v1/auth/refresh', {
        data: { refreshToken: tokens.refreshToken },
      })
      expect(response.status()).toBe(401)
    })
  })

  test('Refresh rotation blocks replay and revokes the compromised token family', async ({ request }) => {
    await withRegisteredCustomer(request, async (_account, tokens) => {
      const first = await request.post('/v1/auth/refresh', {
        data: { refreshToken: tokens.refreshToken },
      })
      expect(first.status()).toBe(200)
      const rotated = await first.json()
      expect(rotated.refreshToken).not.toBe(tokens.refreshToken)
      expect((await request.post('/v1/auth/refresh', {
        data: { refreshToken: tokens.refreshToken },
      })).status()).toBe(401)
      expect((await request.post('/v1/auth/refresh', {
        data: { refreshToken: rotated.refreshToken },
      })).status()).toBe(401)
      const client = prisma()
      try {
        const family = await client.authSession.findUnique({
          where: { tokenHash: createHash('sha256').update(tokens.refreshToken).digest('hex') },
        })
        expect(family).not.toBeNull()
        expect(await client.authSession.count({
          where: { familyId: family!.familyId, revokedAt: null },
        })).toBe(0)
      } finally { await client.$disconnect() }
    })
  })

  test('Logout revokes presented refresh token and does not expose token in response', async ({ request }) => {
    await withRegisteredCustomer(request, async (_account, tokens) => {
      const response = await request.post('/v1/auth/logout', {
        data: { refreshToken: tokens.refreshToken },
      })
      expect(response.status()).toBe(200)
      expect(await response.json()).toEqual({ loggedOut: true })
      const client = prisma()
      try {
        const session = await client.authSession.findUnique({
          where: { tokenHash: createHash('sha256').update(tokens.refreshToken).digest('hex') },
        })
        expect(session?.revokedAt).toBeTruthy()
      } finally { await client.$disconnect() }
      expect((await request.post('/v1/auth/refresh', {
        data: { refreshToken: tokens.refreshToken },
      })).status()).toBe(401)
    })
  })

  test('Customer token and credentials do not grant Admin access', async ({ request }) => {
    await withRegisteredCustomer(request, async (account, tokens) => {
      expect((await request.post('/v1/admin/auth/login', { data: account })).status()).toBe(401)
      expect((await request.get('/v1/admin/auth/me', {
        headers: bearer(tokens.accessToken),
      })).status()).toBe(403)
    })
  })

  test('Authorized STAFF login works; disabling staff revokes next protected access', async ({ request }) => {
    await withRegisteredCustomer(request, async (account, tokens) => {
      const client = prisma()
      try {
        await client.user.update({ where: { id: tokens.user.id }, data: { role: 'STAFF' } })
      } finally { await client.$disconnect() }
      const login = await request.post('/v1/admin/auth/login', { data: account })
      expect(login.status()).toBe(200)
      const admin = await login.json()
      expect((await request.get('/v1/admin/auth/me', { headers: bearer(admin.accessToken) })).status()).toBe(200)
      const next = prisma()
      try {
        await next.user.update({ where: { id: tokens.user.id }, data: { status: 'DISABLED' } })
      } finally { await next.$disconnect() }
      expect((await request.get('/v1/admin/auth/me', { headers: bearer(admin.accessToken) })).status()).toBe(401)
      expect((await request.post('/v1/admin/auth/login', { data: account })).status()).toBe(401)
    })
  })

  test('Successful login creates an audit event linked to the account', async ({ request }) => {
    await withRegisteredCustomer(request, async (account, tokens) => {
      expect((await request.post('/v1/auth/login', { data: account })).status()).toBe(200)
      const client = prisma()
      try {
        expect(await client.auditEvent.count({
          where: { actorId: tokens.user.id, action: 'customer.login' },
        })).toBeGreaterThan(0)
      } finally { await client.$disconnect() }
    })
  })
})
